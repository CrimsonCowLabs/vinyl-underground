func TestTagEdit(t *testing.T) {
	tests.Init(t, false)
	log.SetLevel(log.LevelFatal)
	RegisterFailHandler(Fail)
	RunSpecs(t, "Tag Edit Suite")
}

// The cover writes are tested on a real database (an album, its folders and its Corrections);
// db.Db() is a process-wide singleton, so the suite shares one.
var _ = BeforeSuite(func() {
	DeferCleanup(configtest.SetupConfig())
	conf.Server.DbPath = filepath.Join(GinkgoT().TempDir(), "tagedit.db") + "?_journal_mode=WAL"
	DeferCleanup(db.Init(context.Background()))
})
